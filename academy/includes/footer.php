function toggleWaChatCard(e) {
    if (e) e.stopPropagation();
    const card = document.getElementById('floatingWaCard');
    if (card) {
        if (card.style.display === 'none' || card.style.display === '') {
            card.style.display = 'block';
        } else {
            card.style.display = 'none';
        }
    }
}

